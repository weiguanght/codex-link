#!/usr/bin/env python3
"""Rebuild the iOS syntax asset from pinned npm archives, supplied as arguments."""
import argparse
import hashlib
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'ios/CodexLink/SyntaxAssets'
LANGUAGES = ('elixir', 'haskell', 'julia', 'latex', 'ocaml', 'perl', 'pgsql', 'scala', 'sql', 'verilog')
HIGHLIGHT_SHA = 'accbfaaab745088609b4eea2bdca2ad62f1f1dd27304e0f8df65cfe0fe042143'
PRISM_SHA = 'ac16a9106a28c53b6a6313993c816a3a02525fdfefd7614fc1703df915a9fc11'


def checked_archive(path, checksum):
    if hashlib.sha256(path.read_bytes()).hexdigest() != checksum:
        raise ValueError(f'Unexpected upstream archive digest: {path}')
    return tarfile.open(path, 'r:gz')


def read(archive, member):
    with archive.extractfile('package/' + member) as source:
        return source.read().decode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('highlight', type=Path, help='highlight.js-11.12.0.tgz')
    parser.add_argument('prism', type=Path, help='prismjs-1.30.0.tgz')
    args = parser.parse_args()

    def module(source):
        return '(function () {\nconst module = { exports: {} };\n' + source.rstrip() + '\nreturn module.exports;\n})()'

    with checked_archive(args.highlight, HIGHLIGHT_SHA) as highlight, checked_archive(args.prism, PRISM_SHA) as prism:
        parts = [
            '// Generated by scripts/bundle-syntax.py from Highlight.js 11.12.0 and Prism 1.30.0.',
            '(function () {',
            'const hljs = ' + module(read(highlight, 'lib/core.js')) + ';',
        ]
        for name in LANGUAGES:
            grammar = module(read(highlight, f'lib/languages/{name}.js'))
            parts.append(f'hljs.registerLanguage("{name}", {grammar});')
        parts.extend(read(prism, name).rstrip() for name in (
            'components/prism-core.min.js', 'components/prism-agda.min.js'))
        parts.extend([(ROOT / 'scripts/syntax-adapter.js').read_text().rstrip(), '})();', ''])
        script = '\n'.join(parts)
        script = '\n'.join(line.rstrip(' \t') for line in script.split('\n'))
        (ASSETS / 'SyntaxHighlighter.js').write_text(script, encoding='utf-8')
        (ASSETS / 'HighlightJS-LICENSE').write_text(read(highlight, 'LICENSE'), encoding='utf-8')
        (ASSETS / 'Prism-LICENSE').write_text(read(prism, 'LICENSE'), encoding='utf-8')


if __name__ == '__main__':
    main()
